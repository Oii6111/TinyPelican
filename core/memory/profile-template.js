function flatten(profile, entries = []) {
  for (const [key, value] of Object.entries(profile || {})) {
    if (value && typeof value === 'object' && !Array.isArray(value)) flatten(value, entries);
    else entries.push([key, value]);
  }
  return entries;
}

function profileGaps(profile = {}, skipped = [], { includeBusiness = false } = {}) {
  const entries = flatten(profile);
  const business = includeBusiness || entries.some(([key, value]) => /关系|身份|角色/.test(key) && /客户|商务|供应商|合作伙伴|采购|销售/.test(String(value)));
  return TEMPLATE.flatMap((group) => group.fields).map((field) => {
    const names = new Set([field.label, ...field.aliases]);
    const values = entries.filter(([key]) => names.has(key)).map(([, value]) => String(value ?? '').trim());
    const refused = values.some((value) => /不愿透露|不想谈|不方便说|不适用|暂不询问/.test(value));
    const known = values.some((value) => value && !/^(未知|不详|待确认|待了解|暂无|未填写|不确定|null|undefined)$/i.test(value));
    const state = skipped.includes(field.id) || refused ? 'skipped' : known ? 'known' : 'missing';
    return { ...field, state, eligible: state === 'missing' && field.method === 'ask' && field.applicable !== 'owner' && (field.applicable !== 'business' || business) };
  }).sort((left, right) => left.priority - right.priority);
}

function mergeProfile(current = {}, patch = {}) {
  const merged = { ...current };
  for (const [key, value] of Object.entries(patch)) {
    if (['__proto__', 'constructor', 'prototype'].includes(key)) continue;
    merged[key] = value && typeof value === 'object' && !Array.isArray(value)
      ? mergeProfile(current[key] && typeof current[key] === 'object' ? current[key] : {}, value)
      : value;
  }
  return merged;
}

function hasProfileValue(profile, section, name, value) {
  const template = TEMPLATE.find((group) => group.section === section)?.fields.find((field) => field.label === name || field.aliases.includes(name));
  const names = new Set(template ? [template.label, ...template.aliases] : [name]);
  const normalize = (text) => String(text ?? '').replace(/\s+/g, '').toLowerCase();
  return flatten(profile).some(([key, known]) => names.has(key) && normalize(known) === normalize(value));
}

