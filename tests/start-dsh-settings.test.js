// scripts/start-dsh.js 自己那份 settings.yaml 写入。
// 以前这里是整份覆盖：跑一次排障脚本，DSH 自己写的 permission / llm-pi-ai /
// ui-onboarding（内测声明确认）和 agent-default-model.reasoningEffort（用户选的推理等级）
// 就全没了。这里锁住「别人的块原样保留 + 幂等」，以及能力声明与核心同一套判定。
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { writeDshSettings, modelFromConfig } = require('../scripts/start-dsh');

function tmpHome(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tnp-start-dsh-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

function readSettings(home) {
  return fs.readFileSync(path.join(home, 'settings.yaml'), 'utf8');
}

function deepseekConfig() {
  return {
    engine: {
      provider: 'deepseek',
      providers: { deepseek: { baseUrl: 'https://api.deepseek.com/v1', apiKey: 'sk-deepseek-test', model: 'deepseek-flash' } }
    }
  };
}

test('start-dsh：写入时保留 DSH 自己写的顶层块与推理等级', (t) => {
  const home = tmpHome(t);
  fs.writeFileSync(path.join(home, 'settings.yaml'), [
    '# generated by TinyPelican (core/agent/dsh-client.js): model comes from Settings → 模型服务',
    'agent-default-model:',
    '  provider: deepseek-official',
    '  model: "stale-model"',
    '  reasoningEffort: high',
    '',
    'permission:',
    '  defaultPreset: read-only',
    '',
    'llm-pi-ai:',
    '  providers:',
    '    packy:',
    '      apiKeyEnv: PACKY_API_KEY',
    '',
    'ui-onboarding:',
    '  welcomeNoticeVersion: "2026-08-13.1"',
    ''
  ].join('\n'), 'utf8');

  const model = modelFromConfig(deepseekConfig());
  assert.strictEqual(writeDshSettings(home, model), 'updated');
  const text = readSettings(home);
  // 别人的块（含嵌套）一字不动
  assert.match(text, /permission:\n {2}defaultPreset: read-only/);
  assert.match(text, /llm-pi-ai:\n {2}providers:\n {4}packy:\n {6}apiKeyEnv: PACKY_API_KEY/);
  assert.match(text, /ui-onboarding:\n {2}welcomeNoticeVersion: "2026-08-13\.1"/);
  // 我们的子键照旧覆盖，DSH 的子键保留
  assert.match(text, /agent-default-model:\n {2}provider: deepseek-official\n {2}model: "deepseek-flash"\n {2}reasoningEffort: high/);
  assert.doesNotMatch(text, /stale-model/);
  // 幂等：DSH 会监听这个文件，反复写会一直热重载
  assert.strictEqual(writeDshSettings(home, model), 'same');
});

test('start-dsh：能力声明与核心同一套（视觉模型声明、纯文本不声明）', (t) => {
  const home = tmpHome(t);
  writeDshSettings(home, modelFromConfig(deepseekConfig()));
  let text = readSettings(home);
  assert.match(text, /inputModalities: \[text, image\]/);
  assert.match(text, /systemPromptUpdate: in-history/);

  const ollama = modelFromConfig({ engine: { provider: 'ollama', providers: { ollama: { baseUrl: 'http://127.0.0.1:11434/v1', model: 'qwen3:8b' } } } });
  writeDshSettings(home, ollama);
  text = readSettings(home);
  assert.match(text, /model: "qwen3:8b"/);
  assert.doesNotMatch(text, /inputModalities/);
  assert.doesNotMatch(text, /systemPromptUpdate/);
});

test('start-dsh：没有成套配置时回到 DSH 默认模型，别人的块照样保留', (t) => {
  const home = tmpHome(t);
  fs.writeFileSync(path.join(home, 'settings.yaml'), [
    '# generated by TinyPelican (core/agent/dsh-client.js): model comes from Settings → 模型服务',
    'agent-default-model:',
    '  provider: deepseek-official',
    '  model: "old-model"',
    'permission:',
    '  defaultPreset: auto',
    ''
  ].join('\n'), 'utf8');

  assert.strictEqual(writeDshSettings(home, null), 'updated');
  const text = readSettings(home);
  assert.match(text, /model: "deepseek-flash"/);   // FALLBACK：DSH 自带默认模型
  assert.doesNotMatch(text, /old-model/);
  assert.doesNotMatch(text, /baseURL/);            // 不留半套配置
  assert.match(text, /permission:\n {2}defaultPreset: auto/);
});
