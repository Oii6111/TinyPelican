// 内置 DSH 的模型配置：小鹈鹕设置里的「模型 + 地址 + Key」必须成套地写进 DSH_HOME/settings.yaml。
// 曾经的坑：打包版默认 provider 是 siliconflow（模型 Qwen/Qwen3.5-9B、Key 为空），
// 用户只在 deepseek 里填了 Key，结果写出「Qwen 模型 + 没钥匙」的配置，DSH 里发消息报「API 密钥无效」。
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { writeGeneratedDshSettings, effectiveEngineProvider, buildDshEnv } = require('../core/agent/dsh-client');

function tmpHome(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tnp-dsh-settings-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

function configWithKeyOnDeepSeek() {
  return {
    engine: {
      provider: 'siliconflow',
      providers: {
        siliconflow: { baseUrl: 'https://api.siliconflow.cn/v1', apiKey: '', model: 'Qwen/Qwen3.5-9B' },
        deepseek: { baseUrl: 'https://api.deepseek.com/v1', apiKey: 'sk-deepseek-test', model: 'deepseek-flash' }
      }
    }
  };
}

test('DSH 模型配置：选中的 provider 没 Key 时，退到真有 Key 的那个', (t) => {
  const home = tmpHome(t);
  assert.strictEqual(writeGeneratedDshSettings(home, configWithKeyOnDeepSeek()), true);
  const text = fs.readFileSync(path.join(home, 'settings.yaml'), 'utf8');
  assert.match(text, /model: "deepseek-flash"/);
  assert.match(text, /baseURL: "https:\/\/api\.deepseek\.com\/v1"/);
  assert.doesNotMatch(text, /Qwen/);
  assert.doesNotMatch(text, /siliconflow/);
});

test('DSH 模型配置：内容没变就不重写（免得 DSH 反复热重载）', (t) => {
  const home = tmpHome(t);
  writeGeneratedDshSettings(home, configWithKeyOnDeepSeek());
  const before = fs.statSync(path.join(home, 'settings.yaml')).mtimeMs;
  assert.strictEqual(writeGeneratedDshSettings(home, configWithKeyOnDeepSeek()), false);
  assert.strictEqual(fs.statSync(path.join(home, 'settings.yaml')).mtimeMs, before);
});

test('DSH 模型配置：一个可用 provider 都没有时，回到 DSH 默认模型（不留半套配置）', (t) => {
  const home = tmpHome(t);
  const cfg = {
    engine: {
      provider: 'siliconflow',
      providers: { siliconflow: { baseUrl: 'https://api.siliconflow.cn/v1', apiKey: '', model: 'Qwen/Qwen3.5-9B' } }
    }
  };
  assert.strictEqual(writeGeneratedDshSettings(home, cfg), true);
  const text = fs.readFileSync(path.join(home, 'settings.yaml'), 'utf8');
  assert.match(text, /model: "deepseek-flash"/);
  assert.doesNotMatch(text, /Qwen/);         // 不能带模型
  assert.doesNotMatch(text, /baseURL/);      // 也不能带地址
});

test('DSH 模型配置：配置变回不可用时，把之前写进去的模型/地址覆盖掉', (t) => {
  const home = tmpHome(t);
  const cfg = configWithKeyOnDeepSeek();
  assert.strictEqual(writeGeneratedDshSettings(home, cfg), true);
  const file = path.join(home, 'settings.yaml');
  assert.match(fs.readFileSync(file, 'utf8'), /baseURL: "https:\/\/api\.deepseek\.com\/v1"/);

  cfg.engine.providers.deepseek.apiKey = '';
  assert.strictEqual(writeGeneratedDshSettings(home, cfg), true);
  const text = fs.readFileSync(file, 'utf8');
  assert.doesNotMatch(text, /baseURL/);
  assert.match(text, /model: "deepseek-flash"/);
});

test('DSH 模型配置：选中且可用时用选中的那个；没 Key 时不算可用', () => {  const cfg = configWithKeyOnDeepSeek();
  assert.strictEqual(effectiveEngineProvider(cfg).name, 'deepseek');
  cfg.engine.provider = 'deepseek';
  assert.strictEqual(effectiveEngineProvider(cfg).name, 'deepseek');
  cfg.engine.providers.deepseek.apiKey = '';
  assert.strictEqual(effectiveEngineProvider(cfg), null);
});

test('DSH 模型配置：没填任何 Key 时，不能悄悄退到本地 Ollama', () => {
  // 打包版默认配置长这样：选中 siliconflow（空 Key）+ 预设里的 ollama（qwen3:8b、无 Key）
  const cfg = configWithKeyOnDeepSeek();
  cfg.engine.providers.deepseek.apiKey = '';
  cfg.engine.providers.ollama = { baseUrl: 'http://127.0.0.1:11434/v1', apiKey: '', model: 'qwen3:8b' };
  assert.strictEqual(effectiveEngineProvider(cfg), null);

  // 但用户显式选了 Ollama 就得用 Ollama（本地服务不需要 Key）
  cfg.engine.provider = 'ollama';
  assert.strictEqual(effectiveEngineProvider(cfg).name, 'ollama');
});

test('DSH 模型配置：设置里的 Key 覆盖环境里残留的 DEEPSEEK_API_KEY', (t) => {
  const home = tmpHome(t);
  const prev = process.env.DEEPSEEK_API_KEY;
  process.env.DEEPSEEK_API_KEY = 'sk-stale-from-env';
  try {
    const env = buildDshEnv(home, configWithKeyOnDeepSeek());
    assert.strictEqual(env.DEEPSEEK_API_KEY, 'sk-deepseek-test');
    assert.strictEqual(env.DSH_HOME, home);
  } finally {
    if (prev === undefined) delete process.env.DEEPSEEK_API_KEY;
    else process.env.DEEPSEEK_API_KEY = prev;
  }
});

// 下面两条是白标相关：DSH 会把用户级的设置写在同一份 settings.yaml 里，
// 我们整份重写会静默抹掉它们（最明显的后果是「内测声明」反复弹回来）。

test('DSH 设置：DSH 自己写的顶层键在重写时原样保留', (t) => {
  const home = tmpHome(t);
  const file = path.join(home, 'settings.yaml');
  fs.writeFileSync(file, [
    '# generated by TinyPelican (core/agent/dsh-client.js): model comes from Settings → 模型服务',
    'agent-default-model:',
    '  provider: deepseek-official',
    '  model: "stale-model"',
    'permission:',
    '  defaultPreset: read-only',
    'some-plugin:',
    '  nested:',
    '    value: 1',
    ''
  ].join('\n'), 'utf8');

  assert.strictEqual(writeGeneratedDshSettings(home, configWithKeyOnDeepSeek()), true);
  const text = fs.readFileSync(file, 'utf8');
  // 别人的键（含嵌套）必须一字不动地留着
  assert.match(text, /permission:\n {2}defaultPreset: read-only/);
  assert.match(text, /some-plugin:\n {2}nested:\n {4}value: 1/);
  // 我们拥有的键照旧被当前配置覆盖
  assert.match(text, /model: "deepseek-flash"/);
  assert.doesNotMatch(text, /stale-model/);
  // 重复写入仍然幂等（DSH 会监听这个文件，反复写会一直热重载）
  assert.strictEqual(writeGeneratedDshSettings(home, configWithKeyOnDeepSeek()), false);
});

test('DSH 设置：主动写上前端那份欢迎声明版本，终端用户不会再看到内测声明', (t) => {
  const home = tmpHome(t);
  writeGeneratedDshSettings(home, configWithKeyOnDeepSeek());
  const text = fs.readFileSync(path.join(home, 'settings.yaml'), 'utf8');
  const asset = path.resolve(__dirname, '../node_modules/@deepseek-ai/dsh-client-ui-settings-models/lib/client.js');
  const version = /WELCOME_NOTICE_VERSION\s*=\s*"([^"]+)"/.exec(fs.readFileSync(asset, 'utf8'))[1];
  assert.ok(version.length > 0);
  assert.match(text, new RegExp(`welcomeNoticeVersion: "${version.replace(/\./g, '\\.')}"`));
});

// agent-default-model 是我们拥有的键，但 DSH 自己也往里写（dsh-agent-default-model
// 插件保存用户选的推理等级）。整块重写会把它抹掉——表现是模型菜单里的 High 自己变回去。
test('DSH 设置：agent-default-model 里 DSH 写的子键（推理等级）在重写时保留', (t) => {
  const home = tmpHome(t);
  const file = path.join(home, 'settings.yaml');
  fs.writeFileSync(file, [
    '# generated by TinyPelican (core/agent/dsh-client.js): model comes from Settings → 模型服务',
    'agent-default-model:',
    '  provider: deepseek-official',
    '  model: "stale-model"',
    '  reasoningEffort: high',
    ''
  ].join('\n'), 'utf8');

  const cfg = configWithKeyOnDeepSeek();          // deepseek-flash，与旧内容不同 → 触发重写
  assert.strictEqual(writeGeneratedDshSettings(home, cfg), true);
  const text = fs.readFileSync(file, 'utf8');
  assert.match(text, /model: "deepseek-flash"/);  // 我们的两个子键照旧覆盖
  assert.doesNotMatch(text, /stale-model/);
  assert.match(text, /agent-default-model:\n {2}provider: deepseek-official\n {2}model: "deepseek-flash"\n {2}reasoningEffort: high/);
  // 再写一次仍然幂等（推理等级不会让文件一直变、反复热重载）
  assert.strictEqual(writeGeneratedDshSettings(home, cfg), false);
});

// 能力声明：显式列出 models 会整份替换 DSH 内置目录，所以要由我们把内置目录里的
// 能力补回来——但只能给上游真的支持的路线补。漏掉图片声明，zod 会默认成纯文本路由，
// read_image 直接被拒（model "..." does not declare image input）；漏掉 in-history，
// 中途改 system prompt 会重写开头那条 system 消息、把缓存前缀整段作废。
// 反过来，给纯文本上游声明图片，请求会带着图打到上游、由上游报错（更难查）。

function writeWith(cfg) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'tnp-dsh-settings-'));
  writeGeneratedDshSettings(home, cfg);
  return fs.readFileSync(path.join(home, 'settings.yaml'), 'utf8');
}

test('DSH 能力声明：DeepSeek 官方的 deepseek-flash 要声明图片输入 + in-history', () => {
  const text = writeWith(configWithKeyOnDeepSeek());
  assert.match(text, /inputModalities: \[text, image\]/);
  assert.match(text, /systemPromptUpdate: in-history/);
});

test('DSH 能力声明：纯文本模型不声明（deepseek-v4-pro / 本地 qwen3:8b）', () => {
  const cfg = configWithKeyOnDeepSeek();
  cfg.engine.providers.deepseek.model = 'deepseek-v4-pro';
  const deepseek = writeWith(cfg);
  assert.doesNotMatch(deepseek, /inputModalities/);
  assert.doesNotMatch(deepseek, /systemPromptUpdate/);

  const ollama = writeWith({ engine: { provider: 'ollama', providers: { ollama: { baseUrl: 'http://127.0.0.1:11434/v1', model: 'qwen3:8b' } } } });
  assert.match(ollama, /model: "qwen3:8b"/);
  assert.doesNotMatch(ollama, /inputModalities/);
  assert.doesNotMatch(ollama, /systemPromptUpdate/);
});

test('DSH 能力声明：自填的 provider 可以用开关逐项打开', () => {
  const cfg = { engine: { provider: 'ollama', providers: { ollama: { baseUrl: 'http://127.0.0.1:11434/v1', model: 'qwen2.5-vl:7b', imageInput: true } } } };
  const imageOnly = writeWith(cfg);
  assert.match(imageOnly, /inputModalities: \[text, image\]/);
  assert.doesNotMatch(imageOnly, /systemPromptUpdate/);   // 没打开就别替它声明

  cfg.engine.providers.ollama.inHistorySystemPrompt = true;
  const both = writeWith(cfg);
  assert.match(both, /inputModalities: \[text, image\]/);
  assert.match(both, /systemPromptUpdate: in-history/);

  // 显式关掉要能压过已知模型表（比如 deepseek-flash 走了不支持图片的网关）
  const off = configWithKeyOnDeepSeek();
  off.engine.providers.deepseek.imageInput = false;
  const known = writeWith(off);
  assert.doesNotMatch(known, /inputModalities/);
  assert.match(known, /systemPromptUpdate: in-history/);   // 另一项不受影响
});

test('DSH 能力声明：两个写入点都要有同一套判定，否则下次启动会被覆盖', () => {
  const required = [
    [/inputModalities: \[text, image\]/, 'inputModalities 声明'],
    [/systemPromptUpdate: in-history/, 'systemPromptUpdate 声明'],
    [/'deepseek-flash': \{ image: true, inHistorySystemPrompt: true \}/, '已知模型表']
  ];
  for (const rel of ['../core/agent/dsh-client.js', '../scripts/start-dsh.js']) {
    const src = fs.readFileSync(path.resolve(__dirname, rel), 'utf8');
    for (const [pattern, what] of required) {
      assert.match(src, pattern, `${rel} 少了 ${what}`);
    }
  }
});

